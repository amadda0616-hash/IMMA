"""
src/validate/check_stage3n_numerical.py

V6 — Stage 3-N (Donut Numerical, fine-tuned) 사후 검증.

★ D-023 사용자 필수 임계값:
- Measure F1   ≥ 0.90 (critical)   ← 논문 0.923
- GDT F1       ≥ 0.95 (critical)   ← 논문 0.965
- Roughness F1 ≥ 0.95 (warning)    ← 논문 1.0
- numerical_accuracy ≥ 0.95 (critical)
- tolerance_match    ≥ 0.90 (critical)
- hallucination_rate < 0.10 (critical)

Inputs
------
- ``--predictions`` : Stage 3-N 출력 폴더 (``*.num.json`` from stage3_numerical.py)
- ``--gt``          : Ground truth 폴더 (``data/vlm/numerical/`` 사람 검수 후)

Predictions format (stage3_numerical.py output)
-----------------------------------------------
::

    {
      "type": "Measure",
      "source": "...",
      "parsed": {
        "nominal": 25.0,
        "tolerance": {"upper": 0.05, "lower": -0.05},
        "unit": "mm"
      },
      "raw_seq": "..."
    }

GT format (training data, after human review)
---------------------------------------------
::

    {
      "type": "Measure",
      "nominal": 25.0,
      "tolerance": {"upper": 0.05, "lower": -0.05},
      "unit": "mm"
    }

Optional ``_review`` block is auto-stripped.

CLI
---
::

    python -m src.validate.check_stage3n_numerical \\
        --predictions outputs/sample/numerical/ \\
        --gt data/vlm/numerical/
"""
